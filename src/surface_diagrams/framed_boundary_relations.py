"""Exact small positive relations in a disk with framed inner boundaries.

Capping the inner boundaries gives a pure braid.  The capping kernel is freely
generated by the inner-boundary twists.  A twist enclosing a set of holes
contributes one turn to the framing of each enclosed hole.  Thus the faithful
Artin braid action, together with these framing counts, checks a framed
relation.  The support drawings are a separate rendering check.
"""

from collections import Counter
from dataclasses import replace
from itertools import combinations

from .braid_actions import reduce_word
from .mapping_classes import ConjugatedTwist, exact_action
from .projected_relations import pc_daisy_terms, pc_rose_terms


def enclosed_boundaries(twist, n):
    """The actual labeled holes inside a conjugated supported twist."""
    if not isinstance(twist, ConjugatedTwist) or twist.half:
        raise ValueError('Framed boundary relations need full Dehn twists')
    if twist.first + twist.points - 1 > n or any(
            abs(letter) >= n for letter in twist.conjugator):
        raise ValueError('Twist exceeds the inner-boundary disk')
    enclosed = set(range(twist.first, twist.first + twist.points))
    for letter in reversed(twist.conjugator):
        index = abs(letter)
        enclosed = {index + 1 if point == index else
                    index if point == index + 1 else point
                    for point in enclosed}
    return tuple(sorted(enclosed))


def framed_outer_certificate(n, factors, outer_power):
    """Check an ordered positive relation against T_outer^power and holes.

    Return the nonnegative inner-boundary powers on the target side.  Pair
    winding counts provide an independent necessary check; exact Artin action
    checks the full capped braid, not only its abelianization.
    """
    if type(n) is not int or n < 2 or type(outer_power) is not int or outer_power < 1:
        raise ValueError('Choose at least two holes and a positive outer power')
    factors = tuple(factors)
    if not factors or any(factor.power != 1 for factor in factors):
        raise ValueError('Use positive unit Dehn twists')
    supports = tuple(enclosed_boundaries(factor, n) for factor in factors)
    pairs = Counter(pair for block in supports for pair in combinations(block, 2))
    if any(pairs[pair] != outer_power for pair in combinations(range(1, n + 1), 2)):
        raise ValueError('Pair winding counts do not match the outer twist')
    word = tuple(letter for factor in factors for letter in factor.word)
    target = ConjugatedTwist((), 1, n, power=outer_power)
    if exact_action(word, n) != exact_action(target.word, n):
        raise ValueError('Exact capped braid action does not match the outer twist')
    powers = tuple(sum(point in block for block in supports) - outer_power
                   for point in range(1, n + 1))
    if any(power < 0 for power in powers):
        raise ValueError('A negative inner-boundary correction is required')
    return powers


def four_triple_relations():
    """A four-triple T_outer² relation and its first two lantern expansions.

    The conjugators specify the actual isotopy classes, not merely the sets
    of enclosed holes.  Replacing a triple twist by its three pair twists is
    the framed lantern relation after moving its boundary corrections to the
    target side; each result is checked again in the framed braid model.
    """
    seed = (
        ConjugatedTwist((), 1, 3),
        ConjugatedTwist((-3,), 1, 3),
        ConjugatedTwist((2, -3), 1, 3),
        ConjugatedTwist((1, 2, -3), 1, 3),
    )
    results = []
    for expanded in ((), (3,), (2, 3)):
        factors = tuple(term for index, factor in enumerate(seed)
                        for term in (pc_rose_terms(factor) if index in expanded
                                     else (factor,)))
        powers = framed_outer_certificate(4, factors, 2)
        results.append({'factors': factors, 'inner_powers': powers,
                        'expanded_seed_indices': expanded})
    return tuple(results)


def five_boundary_lifts():
    """Lift the three four-triple relations to a fifth framed boundary.

    Let P = T_1234 and L be the ordered product of the four petals enclosing
    the fifth hole and one old hole. The *framed* daisy says
    P L = T_12345 (T_1 T_2 T_3 T_4) T_5³. Thus P and L commute, since
    the outer and inner-boundary twists are central. Squaring gives
    P² L² = T_12345² (T_1 T_2 T_3 T_4)² T_5⁶. Substitute each checked
    four-triple factorization for P², retaining its boundary corrections.
    """
    prefix, *petals = pc_daisy_terms(ConjugatedTwist((), 1, 5))
    assert prefix == ConjugatedTwist((), 1, 4)
    petals = tuple(petals)
    results = []
    for parent in four_triple_relations():
        core = parent['factors']
        factors = core + petals + petals
        powers = framed_outer_certificate(5, factors, 2)
        results.append({'factors': factors, 'inner_powers': powers,
                        'core_factor_count': len(core),
                        'expanded_seed_indices': parent['expanded_seed_indices']})
    return tuple(results)


def five_boundary_mixed_lantern():
    """A new five-hole type by Hurwitz moves followed by inverse lantern.

    Begin with the 14-factor lift. Move its fourth factor T_23 past the
    following T_24, T_34, and T_45. The next three factors are then precisely
    T_23, T_35, T_25, whose capped action is the twist T_235 routed under
    hole 4. Their framed lantern has a T_2 T_3 T_5 correction. The final
    equality is independently checked in the framed braid model.
    """
    from .twist_simplify import simplify_twist

    factors = list(five_boundary_lifts()[1]['factors'])
    for index in (3, 4, 5):
        moving, crossed = factors[index:index + 2]
        changed = simplify_twist(replace(
            crossed, conjugator=reduce_word(moving.word + crossed.conjugator)),
            strands=5, max_states=64)
        if exact_action(moving.word + crossed.word, 5) != exact_action(
                changed.word + moving.word, 5):
            raise ValueError('Hurwitz move failed its exact disk check')
        factors[index:index + 2] = (changed, moving)
    triple = ConjugatedTwist((-4,), 2, 3)
    local_word = tuple(letter for factor in factors[6:9] for letter in factor.word)
    if exact_action(local_word, 5) != exact_action(triple.word, 5):
        raise ValueError('Three pair twists do not match the inverse lantern')
    factors[6:9] = (triple,)
    factors = tuple(factors)
    powers = framed_outer_certificate(5, factors, 2)
    return {'name': 'five-hole-mixed-lantern-12', 'factors': factors,
            'inner_powers': powers, 'hurwitz_positions': (4, 5, 6),
            'lantern_support': (2, 3, 5)}
