"""Necessary pure marked-sphere characters; zero does not prove identity."""
from itertools import combinations
from .alternative_thirty_audit import pure_linking_certificate


def sphere_linking_character(word, strands=6, *, max_letters=100000):
    """Retain an integral character detecting some nonidentity sphere classes.

    Disk pure-braid linking coordinates add under product. The kernel of
    B_n -> Mod(S^2,n) is normally generated by the sphere relation and the
    central full twist. Their linking vectors are vertex stars and the
    all-ones vector. Every four-distinct-label rectangle below annihilates
    them, including all label permutations. Thus a nonzero character proves
    nonidentity in the marked-sphere mapping class group. Zero is inconclusive;
    no central spherical-braid equality or genus-two lift sign is determined.
    """
    if type(strands) is not int or strands<4:
        raise ValueError('The four-label character needs at least four strands')
    word=tuple(word)
    linking=pure_linking_certificate(word,strands,max_letters=max_letters)
    matrix=linking['linking_matrix'];records=[]
    for i,j,k,l in combinations(range(strands),4):
        for a,b,c,d in ((i,j,k,l),(i,j,l,k)):
            value=matrix[a][b]+matrix[c][d]-matrix[a][c]-matrix[b][d]
            records.append(dict(labels=(a+1,b+1,c+1,d+1),value=value))
    witness=next((r for r in records if r['value']),None)
    return dict(source_word=word,disk_linking=linking,rectangle_characters=tuple(records),
        nonzero_character=witness,nonidentity_sphere_proved=witness is not None,
        zero_is_inconclusive=True,genus_two_lift_sign_claimed=False,
        method='L_ab + L_cd - L_ac - L_bd on four distinct labels',
        scope='Necessary character of a PURE marked-sphere mapping class only. A nonzero value proves nonidentity; all zero values do not prove identity. No strand is deleted or converted to a boundary.')
