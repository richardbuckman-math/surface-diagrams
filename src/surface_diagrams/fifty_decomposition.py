"""Extract the standard twenty-unit tail from the actual fifty-unit branch.

The remaining thirty units are NOT asserted to be W1. Their permutation
orbits are an independently recorded obstruction to that particular claim.
They close instead through the separately checked five-point boundary model.
"""
