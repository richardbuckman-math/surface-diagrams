def unit_factors(factors):
    """Split positive two-point twists into their identical half-twist units."""
    factors=tuple(factors)
    if any(f.points!=2 or getattr(f,'sign',1)!=1 for f in factors):
        raise ValueError('Expected positive two-point factors')
    units=tuple(replace(f,id=f.id+'.unit'+str(i+1),half=True,power=1)
                for f in factors for i in range(f.power*(1 if f.half else 2)))
    if reduce_word(product(units)+inverse_word(product(factors))):
        raise ValueError('Unit expansion failed its free-word certificate')
    return units


def permutation_orbits(factors):
    """Orbits of the permutation group generated by the factor images."""
    components=[{i} for i in range(1,7)]
    for f in factors:
        if not f.half or f.power%2==0:
            continue
        a,b=half_endpoints(f.mapping_class)
        one=next(c for c in components if a in c)
        two=next(c for c in components if b in c)
        if one is not two:
            one.update(two);components.remove(two)
    return tuple(sorted(tuple(sorted(c)) for c in components))


def extract_twenty_block(factors):
    """Seven Hurwitz moves and a certified sphere rechart isolate twenty.

    This consumes the actual positive endpoint, not its optional displayed
    support representatives. Each local disk equality is proved formally;
    the one sphere change retains its complete disk discrepancy and lift.
    No identity assumption on the full fifty is used to prove the twenty.
    """
    state=tuple(factors)
    if len(unit_factors(state))!=50:
        raise ValueError('Expected the fifty-unit positive endpoint')
    target=next((i for i,f in enumerate(state) if f.id=='alternate.C4.rose.3'),None)
    if target is None or target+1>=len(state) or state[target+1].id!='F3':
        raise ValueError('Expected the transported {5,6} pair immediately before F3')
    if state[target].half or state[target].power!=1:
        raise ValueError('Expected one full pair twist')
    stages=[dict(kind='start',title='The positive fifty-unit endpoint',factors=state)]

    def move(source,destination,title):
        nonlocal state
        record=research_hurwitz_move(state,source,destination)
        state=record['factors'];stages.append(dict(record,title=title))

    move(target+1,target,'Move F3 up: transport the adjacent {5,6} pair')
    index=target+1;before=state[index]
    after=replace(before,conjugator=(),first=5)
    check=check_support_replacement(before.mapping_class,after.mapping_class,max_cuts=24)
    state=state[:index]+(after,)+state[index+1:]
    stages.append(dict(kind='disk_rewrite' if check['disk_equal'] else 'sphere_rewrite',
        title=('Use the exact disk representative T56' if check['disk_equal'] else
               'SPHERE MOVE: rechart the transported pair as the round T56'),
        factors=state,local_before=(before,),local_after=(after,),
        disk_equality=check['disk_equal'],disk_discrepancy=check['disk_discrepancy'],
        sphere_certificate=check['sphere_certificate'],lift_homology=check['lift_homology']))
    tail=next((i for i,f in enumerate(state) if f.id=='sphere.A1.1'),None)
    if tail is None or tail<=index:
        raise ValueError('Missing the eighteen-unit positive sphere tail')
    while index<tail-1:
        move(index,index+1,'Move the round T56 down, conjugating the crossed factor')
        index+=1
    thirty,twenty=state[:index],state[index:]
    if (len(unit_factors(thirty)),len(unit_factors(twenty)))!=(30,20):
        raise ValueError('The extracted blocks have the wrong unit counts')
    a=(4,3,2,1,1,2,3,4)
    model=(5,5)+a+(5,5)+a
    if reduce_word(product(twenty)+inverse_word(model)):
        raise ValueError('The eighteen-unit tail is not the prescribed literal word')
    relator=(5,)+a+(5,)
    # Twenty = sigma5 * R^2 * sigma5^-1, by free cancellation alone.
    telescope=reduce_word(model+inverse_word((5,)+relator*2+(-5,)))
    if telescope:
        raise ValueError('The standard twenty-block word does not telescope')
    sphere=sphere_chain_certificate(model);lift=homology_action(model)
    if not sphere['certified'] or lift!=IDENTITY:
        raise ValueError('The extracted twenty block is not sphere/lift trivial')
    # Reflect the standard chain: Delta sigma_i Delta^-1 = sigma_(6-i).
    delta=(1,2,3,4,5,1,2,3,4,1,2,3,1,2,1)
    frame=(5,)+delta
    w0=(1,2,3,4,5,5,4,3,2,1)*2
    expected=frame+w0+inverse_word(frame)
    if exact_action(model)!=exact_action(expected):
        raise ValueError('The extracted twenty is not the declared disk conjugate of W0')
    orbits=permutation_orbits(thirty)
    return dict(stages=tuple(stages),thirty_factors=thirty,twenty_factors=twenty,
        thirty_units=unit_factors(thirty),twenty_units=unit_factors(twenty),
        twenty_word=model,twenty_relator=relator,twenty_telescope=telescope,
        twenty_sphere_certificate=sphere,twenty_lift_homology=lift,
        standard_twenty_word=w0,standard_twenty_frame=frame,
        standard_twenty_disk_certificate=dict(method='faithful Artin action',equal=True),
        thirty_permutation_orbits=orbits,
        thirty_alone_hurwitz_equivalent_to_w1=False if len(orbits)>1 else None,
        thirty_permutation_obstruction_to_w1=len(orbits)>1,
        thirty_standard_block_identified=False,complete_structural_derivation_found=False,
        sphere_move_count=sum(s['kind']=='sphere_rewrite' for s in stages),
        scope='An explicit standard twenty is isolated. The thirty remainder still needs its own derivation; count alone is insufficient.')


def recognize_thirty_boundary(factors):
    """An independent five-point-disk proof of the actual thirty remainder.

    The witnesses use point 6 as infinity. One {3,6} pair curve becomes
    its complementary four-point curve, increasing the expanded disk-core
    length by ten. This is not a Hurwitz identification with the standard
    thirty W1. Each sphere chart change, the exact disk boundary relation,
    and the final lift-preserving cap are separate certified operations.
    """
    state=tuple(factors)
    if len(unit_factors(state))!=30:
        raise ValueError('Expected the thirty-unit positive remainder')
    witnesses={
        'cross.P12':((),1,2),
        'alternate.HL1.1':((2,),1,2),
        'alternate.HL1.2':((-1,4,3,2,2,2),3,2),
        'alternate.HL1.3':((4,3,2),1,2),
        'alternate.HL2.1':((2,),1,2),
        'alternate.HL2.2':((-1,4,3,2,2,2),3,2),
        'alternate.P15.remaining':((4,3,2),1,2),
        'alternate.C4.rose.1':((-1,4,3,2,2),3,2),
        'alternate.C4.rose.2':((-1,4,4,3,2,-3,-3,-3,2,1),2,4),
        'F3':((-1,4,4,3,2,-3,2),3,2),
        'F6':((2,-3,2,3,3),4,2),
        'new.P26':((),2,2),
        'F9':((3,3,3,1),2,2),
        'F11':((4,3,1,1),2,2),
        'last.P12.square':((),1,2),
        'last.P34.square':((),3,2)}
    if set(f.id for f in state)!=set(witnesses) or len(state)!=len(witnesses):
        raise ValueError('Expected the identified thirty-block factor records')
    stages=[dict(kind='start',title='The actual thirty-unit remainder',factors=state)]
    for index,old in enumerate(tuple(state)):
        conjugator,first,points=witnesses[old.id]
        new=replace(old,conjugator=conjugator,first=first,points=points)
        if old==new:
            continue
        if old.half and half_endpoints(old.mapping_class)!=half_endpoints(new.mapping_class):
            raise ValueError('The five-point chart changes half-twist endpoints')
        if sphere_supported_class(old.mapping_class)!=sphere_supported_class(new.mapping_class):
            raise ValueError('The five-point chart changes a sphere support')
        discrepancy=reduce_word(old.word+inverse_word(new.word))
        sphere=sphere_chain_certificate(discrepancy)
        if not sphere['certified'] or homology_action(discrepancy)!=IDENTITY:
            raise ValueError('The five-point rechart changes the sphere action or lift')
        disk_equal=(old.points==new.points and
                    supported_class(old.mapping_class)==supported_class(new.mapping_class))
        state=state[:index]+(new,)+state[index+1:]
        stages.append(dict(kind='disk_rewrite' if disk_equal else 'sphere_rewrite',
            title=('Use a disk-equal five-point representative of ' if disk_equal else
                   'SPHERE MOVE: put point 6 at infinity for ')+old.id,
            factors=state,local_before=(old,),local_after=(new,),
            disk_equality=disk_equal,disk_discrepancy=discrepancy,
            sphere_certificate=sphere,lift_homology=IDENTITY,
            complementary_pair_to_four_point=(old.points,new.points)==(2,4)))
    five_point=state;word=product(state)
    if any(abs(letter)>4 for letter in word):
        raise ValueError('The proposed disk model still uses point 6')
    boundary=replace(state[0],id='boundary.five.double',conjugator=(),first=1,points=5,power=2,half=False)
    actual,expected=exact_action(word,strands=5),exact_action(boundary.word,strands=5)
    if actual!=expected:
        raise ValueError('The ordered five-point factorization is not the double boundary twist')
    stages.append(dict(kind='disk_boundary_relation',title='Exact five-point disk relation: double outer-boundary twist',
        factors=(boundary,),local_before=state,local_after=(boundary,),
        disk_equality=True,disk_action_certificate=dict(strands=5,actual=actual,expected=expected,equal=True)))
    cap=sphere_chain_certificate(boundary.word)
    if not cap['certified'] or homology_action(boundary.word)!=IDENTITY:
        raise ValueError('The double boundary cap changes the sphere action or genus-two lift')
    stages.append(dict(kind='sphere_rewrite',title='SPHERE MOVE: cap the double boundary around point 6',
        factors=(),local_before=(boundary,),local_after=(),disk_equality=False,
        disk_discrepancy=boundary.word,sphere_certificate=cap,lift_homology=IDENTITY))
    return dict(stages=tuple(stages),five_point_factors=five_point,boundary=boundary,
        disk_core_length=sum(len(f.core) for f in five_point),
        disk_boundary_action=actual,disk_boundary_action_verified=True,
        independent_sphere_identity_proof=True,
        uses_source_identity_as_hypothesis=False,
        hurwitz_equivalence_to_w1_claimed=False,
        scope='Independent exact boundary-action proof; not an elementary Hurwitz route to W1.')


def working_seed_to_legacy_chart():
    """Join Richard's designated working (6,7) to the saved route's source.

    Simultaneous conjugations commute with Hurwitz operations. Undo only
    the three adjacent moves in their final common frame, then remove that
    frame explicitly and check the original disk supports factor by factor.
    """
    from .factorization_explorer import initial_factors
    from .factorization_simplify import six_seven_simplification,apply_simplification
    simple=six_seven_simplification();state=simple['stages'][-1]['factors'];frame=simple['frame']
    stages=[dict(kind='start',title='The working (6,7): 154 braid letters',factors=state)]
    for move in ((8,7),(7,6),(3,2)):
        record=apply_simplification(state,'disk_hurwitz',move);state=record['factors']
        stages.append(dict(record,title='Change the working ordering by an inverse Hurwitz move'))
    record=apply_simplification(state,'global_conjugation',inverse_word(frame));state=record['factors']
    stages.append(dict(record,title='Global conjugation by '+
        ' '.join(map(str,inverse_word(frame)))+' into the saved calculation chart'))
    target=initial_factors()
    checks=[]
    for old,new in zip(state,target):
        if (old.id,old.points,old.power,old.half)!=(new.id,new.points,new.power,new.half):
            raise ValueError('The working seed does not join the saved factor types')
        a,b=supported_class(old.mapping_class),supported_class(new.mapping_class)
        if a!=b:
            raise ValueError('The working seed does not join the saved disk supports')
        checks.append(dict(id=old.id,disk_support_class=a))
    if len(state)!=len(target) or exact_action(product(state))!=exact_action(product(target)):
        raise ValueError('The working seed bridge fails its complete exact disk action')
    stages.append(dict(kind='disk_presentation',title='Use the literal source presentations of the saved route',
        factors=target,disk_support_checks=checks))
    return dict(stages=tuple(stages),initial_frame=frame,final_frame=(),sphere_move_count=0,
        joins_legacy_source=True,scope='Three disk Hurwitz moves, one explicit global conjugation, and exact disk presentations.')
